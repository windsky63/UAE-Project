const {chromium}=require('playwright');
const {expect}=require('@playwright/test');
const fs=require('fs');
const path=require('path');
const os=require('os');

(async()=>{
  const runtime=path.resolve(__dirname,'../runtime');
  const output=path.join(os.tmpdir(),'project-tools-codex-layout-qa');
  fs.mkdirSync(output,{recursive:true});
  const session=JSON.parse(fs.readFileSync(path.join(runtime,'codex-fixture-session.json'),'utf8'));
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
    await page.goto(session.url);
    await page.goto(new URL('/#codex',session.url).href);
    await page.getByTestId('codex-panel').waitFor();
    await expect(page).toHaveTitle(/管理中心/);
    await expect(page.locator('.workspace-drawer')).toBeVisible();
    await expect(page.locator('.workspace-topbar')).toContainText('Codex 对话');
    const labels=await page.locator('.workspace-drawer .v-list-item-title').allTextContents();
    expect(labels.slice(0,2)).toEqual(['工作台','Codex 对话']);
    const sharedTheme=await page.evaluate(()=>getComputedStyle(document.querySelector('.codex-shell')).backgroundColor===getComputedStyle(document.querySelector('.workspace-drawer')).backgroundColor);
    expect(sharedTheme).toBe(true);
    await expect(page.getByLabel('切换浅色主题',{exact:true})).toHaveCount(0);
    await expect(page.locator('.codex-session-list')).toBeVisible();
    await expect(page.getByLabel('对话设置',{exact:true})).toHaveCount(0);
    await page.getByLabel('新建对话',{exact:true}).first().click();
    await expect(page.getByLabel('发送给 Codex 的消息')).toBeEnabled();
    const beforeCount=await page.evaluate(async()=>(await(await fetch('/api/codex/sessions')).json()).items.length);
    await page.getByLabel('新建对话',{exact:true}).first().click();
    const afterCount=await page.evaluate(async()=>(await(await fetch('/api/codex/sessions')).json()).items.length);
    expect(afterCount).toBe(beforeCount);
    const draft=page.getByLabel('发送给 Codex 的消息');
    await draft.fill('读取 fixture.txt，核对预制和安装数量');
    await page.getByLabel('发送消息',{exact:true}).click();
    await page.locator('.codex-assistant').first().waitFor();
    await expect(page.getByLabel('停止生成',{exact:true})).toBeVisible();
    await expect(page.locator('.codex-turn-status')).toContainText('已完成');
    await expect(page.locator('.codex-assistant')).toContainText('预制 2 个、安装 1 个');
    await page.getByRole('button',{name:'读取 fixture.txt 成功'}).click();
    await expect(page.locator('.codex-output')).toContainText('SIMULATION: shop=2, field=1');
    await page.screenshot({path:path.join(output,'codex-chat-desktop.png'),fullPage:true});
    await page.getByLabel('文件记录',{exact:true}).click();
    await expect(page.locator('.codex-file-row')).toContainText('fixture.txt');
    await expect(page.locator('.codex-file-row')).toContainText('读取 · 完成');
    const panelBounds=await page.getByTestId('codex-panel').boundingBox();
    const fileBounds=await page.locator('.codex-files').boundingBox();
    expect(fileBounds.x).toBeGreaterThanOrEqual(panelBounds.x);
    expect(fileBounds.height).toBeLessThanOrEqual(panelBounds.height);
    await page.screenshot({path:path.join(output,'codex-chat-files.png'),fullPage:true});
    await page.getByLabel('关闭文件记录',{exact:true}).click();
    await page.reload();
    await expect(page.locator('.codex-assistant')).toContainText('预制 2 个、安装 1 个');
    await draft.fill('尚未发送的草稿');
    await page.getByRole('listitem').filter({hasText:'工作台'}).click();
    await expect(page.getByRole('heading',{name:'工作台',exact:true})).toBeVisible();
    await page.getByRole('listitem').filter({hasText:'Codex 对话'}).click();
    await expect(draft).toHaveValue('尚未发送的草稿');
    await draft.fill('hang: 验证停止生成');
    await page.getByLabel('发送消息',{exact:true}).click();
    await expect(page.getByLabel('停止生成',{exact:true})).toBeVisible();
    await page.getByRole('listitem').filter({hasText:'文件资料'}).click();
    await expect(page.getByRole('heading',{name:'项目文件',exact:true})).toBeVisible();
    await page.getByRole('listitem').filter({hasText:'Codex 对话'}).click();
    await expect(page.getByLabel('停止生成',{exact:true})).toBeVisible();
    await page.getByLabel('停止生成',{exact:true}).click();
    await expect(page.locator('.codex-turn-status')).toContainText('已停止');
    const renamed='会话管理验证-'+Date.now();
    await page.locator('.codex-session-row.active .codex-session-more').click();
    await page.locator('.codex-session-actions').getByText('重命名',{exact:true}).click();
    await page.getByLabel('会话名称',{exact:true}).fill(renamed);
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await expect(page.locator('.codex-session-row.active')).toContainText(renamed);
    await page.locator('.codex-session-row.active .codex-session-more').click();
    await page.locator('.codex-session-actions').getByText('归档',{exact:true}).click();
    await expect(page.locator('.codex-session-rows')).not.toContainText(renamed);
    await page.locator('.codex-session-view .v-field').click();
    await page.getByRole('option',{name:'已归档',exact:true}).click();
    const target=page.locator('.codex-session-row').filter({hasText:renamed});
    await expect(target).toBeVisible();
    await target.locator('.codex-session-select').click();
    await expect(page.locator('.codex-session-readonly')).toBeVisible();
    await target.locator('.codex-session-more').click();
    await page.locator('.codex-session-actions').getByText('取消归档',{exact:true}).click();
    await page.locator('.codex-session-view .v-field').click();
    await page.getByRole('option',{name:'常用对话',exact:true}).click();
    await target.locator('.codex-session-select').click();
    await target.locator('.codex-session-more').click();
    await page.locator('.codex-session-actions').getByText('删除（移入回收站）',{exact:true}).click();
    await page.locator('.codex-session-view .v-field').click();
    await page.getByRole('option',{name:'回收站',exact:true}).click();
    await expect(target).toBeVisible();
    await target.locator('.codex-session-more').click();
    await page.locator('.codex-session-actions').getByText('恢复对话',{exact:true}).click();
    await page.locator('.codex-session-view .v-field').click();
    await page.getByRole('option',{name:'常用对话',exact:true}).click();
    await target.locator('.codex-session-select').click();
    await expect(page.locator('.codex-assistant')).toContainText('预制 2 个、安装 1 个');
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'打开导航',exact:true}).click();
    await page.getByRole('listitem').filter({hasText:'工作台'}).click();
    await expect(page.getByRole('heading',{name:'工作台',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'打开导航',exact:true}).click();
    await page.getByRole('listitem').filter({hasText:'Codex 对话'}).click();
    await expect(page.getByTestId('codex-panel')).toBeVisible();
    await expect(page.locator('.v-navigation-drawer__scrim')).toBeHidden();
    await expect(page.getByLabel('新建对话',{exact:true}).first()).toBeInViewport();
    const mobileBounds=await page.getByTestId('codex-panel').boundingBox();
    expect(mobileBounds.y).toBeGreaterThanOrEqual(64);
    expect(mobileBounds.y+mobileBounds.height).toBeLessThanOrEqual(845);
    await page.screenshot({path:path.join(output,'codex-chat-mobile.png'),fullPage:true});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
    if(overflow)throw Error('Mobile horizontal overflow');
    const text=await page.locator('body').innerText();
    if(text.includes('PRIVATE_CHAIN_TEST_TOKEN'))throw Error('Private reasoning leaked');
    if(errors.length)throw Error(errors.join('\n'));
    const report={passed:true,protocol:'local fixture; no model calls',browser:'Edge via Playwright; Browser plugin not available',url:page.url(),viewports:['1440x1000','390x844'],screenshots:output,checks:['shared sidebar and header','menu order','shared theme','streaming before completion','command output','structured file record','contained file drawer','refresh restores history','draft preserved across pages','active turn preserved across pages','stop generation','history','mobile navigation and layout','no private reasoning','no browser errors']};
    fs.writeFileSync(path.join(output,'codex-browser-qa.json'),JSON.stringify(report,null,2));
    console.log(JSON.stringify(report));
  }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)});

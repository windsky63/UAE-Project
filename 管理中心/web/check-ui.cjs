const { chromium } = require('playwright');
const { expect } = require('@playwright/test');
const fs = require('fs');
const path = require('path');
const { URL } = require('url');

(async()=>{
  const runtime=path.resolve(__dirname,'../runtime');
  const session=JSON.parse(fs.readFileSync(path.join(runtime,'session.json'),'utf8'));
  const origin=new URL(session.url).origin;
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
  await page.goto(session.url);
  await page.getByRole('heading',{name:'工作台',exact:true}).waitFor();
  await page.waitForTimeout(350);
  await page.locator('.v-snackbar').waitFor({state:'hidden',timeout:10000});
  await page.getByRole('heading',{name:'工具运行状态'}).waitFor();
  await page.screenshot({path:path.join(runtime,'management-desktop.png'),fullPage:true});
  await page.getByRole('listitem').filter({hasText:'FusionLive 同步'}).click();
  await page.getByRole('button',{name:'配置设置',exact:true}).click();
  await page.getByLabel('管道简报标题').waitFor();
  if(!await page.getByLabel('管道简报标题').inputValue())throw Error('Missing real sync configuration');
  await page.getByRole('listitem').filter({hasText:'绿联云上传'}).click();
  await page.getByRole('button',{name:'配置设置',exact:true}).click();
  await page.getByLabel('NAS 目标共享目录').waitFor();
  await page.getByRole('listitem').filter({hasText:'微信与 Codex'}).click();
  await page.getByRole('button',{name:'配置设置',exact:true}).click();
  await page.getByRole('heading',{name:'监听会话',exact:true}).waitFor();
  await page.screenshot({path:path.join(runtime,'management-config.png'),fullPage:true});
  await page.getByRole('listitem').filter({hasText:'文件资料'}).click();
  await page.getByRole('heading',{name:'项目文件',exact:true}).waitFor();
  await page.getByRole('textbox',{name:'搜索文件名 / 项目'}).fill('H4-262');
  await page.waitForTimeout(500);
  await page.screenshot({path:path.join(runtime,'management-files.png'),fullPage:true});
  await page.getByRole('listitem').filter({hasText:'工作台'}).click();
  await page.getByRole('button',{name:'模拟完整流程',exact:true}).click();
  await page.getByText('模拟完整流程已提交',{exact:false}).waitFor();
  await expect.poll(async()=>{
    const data=await page.evaluate(async()=>await (await fetch('/api/tasks?tool=wechat')).json());
    return data.items[0]?.state;
  },{timeout:60000}).toBe('succeeded');
  const tasks=await page.evaluate(async()=>await (await fetch('/api/tasks?tool=wechat')).json());
  if(tasks.items[0].state!=='succeeded')throw Error('Simulation did not succeed');
  await page.getByRole('listitem').filter({hasText:'运行日志'}).click();
  await page.getByRole('heading',{name:'运行日志',exact:true}).last().waitFor();
  await page.getByRole('button',{name:'刷新日志',exact:true}).click();
  await page.getByText('simulation_result.json',{exact:false}).first().waitFor({timeout:10000});
  await page.screenshot({path:path.join(runtime,'management-logs.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'打开导航',exact:true}).click();
  await page.getByRole('listitem').filter({hasText:'工作台'}).click();
  await page.getByRole('heading',{name:'工作台',exact:true}).waitFor();
  await page.locator('.v-navigation-drawer__scrim').waitFor({state:'hidden',timeout:5000});
  await page.locator('.v-snackbar').waitFor({state:'hidden',timeout:10000});
  await page.waitForTimeout(350);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2);
  if(overflow)throw Error('Mobile viewport has horizontal page overflow');
  await page.screenshot({path:path.join(runtime,'management-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1100});
  await page.getByRole('button',{name:'刷新状态',exact:true}).click();
  await page.screenshot({path:path.join(runtime,'management-desktop.png'),fullPage:true});
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync(path.join(runtime,'browser-qa.json'),JSON.stringify({passed:true,browser:'Playwright with local Edge; Browser plugin unavailable',origin,desktop:[1440,1100],mobile:[390,844],console_errors:errors,checked:['overview','sync settings','NAS settings','WeChat settings','file search','actual offline simulation','logs','mobile navigation'],simulation_task:tasks.items[0].id},null,2));
  console.log('Browser QA passed: overview, all settings, file search, actual offline simulation, logs and mobile navigation.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});

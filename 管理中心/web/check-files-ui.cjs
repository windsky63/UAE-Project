const {chromium}=require('playwright');
const {expect}=require('@playwright/test');
const fs=require('fs'),path=require('path'),os=require('os');

(async()=>{
  const runtime=path.resolve(__dirname,'../runtime');
  const session=JSON.parse(fs.readFileSync(path.join(runtime,'file-fixture-session.json'),'utf8'));
  const output=path.join(os.tmpdir(),'project-tools-file-catalog-qa');
  fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1050}});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
    await page.goto(session.url);
    await page.goto(new URL('/#files',session.url).href);
    await expect(page).toHaveTitle(/管理中心/);
    await expect(page.getByRole('heading',{name:'项目文件',exact:true})).toBeVisible();
    const count=page.locator('.file-pagination>span');
    await expect(count).toContainText('32 / 32');
    await expect(page.locator('.file-grid tbody tr')).toHaveCount(20);
    await expect(page.locator('.file-grid')).toContainText('管道布置平面及立面图');
    await page.screenshot({path:path.join(output,'files-desktop.png'),fullPage:false});
    const popup=page.locator('.file-filter-popup');
    await page.getByLabel('筛选 业务类型',{exact:true}).click();
    await expect(popup).toBeVisible();
    await popup.getByRole('button',{name:'全不选',exact:true}).click();
    await popup.locator('.file-filter-choice').filter({hasText:'管道布置平面及立面图'}).locator('input').check();
    await popup.locator('.file-filter-choice').filter({hasText:'电缆桥架布置图'}).locator('input').check();
    await popup.getByRole('button',{name:'应用筛选',exact:true}).click();
    await expect(count).toContainText('31 / 32');
    await page.getByLabel('筛选 业务类型',{exact:true}).click();
    await popup.locator('.file-filter-choice').filter({hasText:'电缆桥架布置图'}).locator('input').uncheck();
    await popup.getByRole('button',{name:'应用筛选',exact:true}).click();
    await expect(count).toContainText('16 / 32');
    await page.getByLabel('筛选 已保存字节',{exact:true}).click();
    await popup.locator('.v-select').filter({hasText:'自定义条件'}).click();
    await page.getByRole('option',{name:'大于等于或不早于',exact:true}).click();
    await popup.getByLabel('条件值（字节）',{exact:true}).fill('20');
    await page.screenshot({path:path.join(output,'files-filter.png'),fullPage:false});
    await popup.getByRole('button',{name:'应用筛选',exact:true}).click();
    await expect(count).toContainText('6 / 32');
    await page.getByLabel('筛选 已保存字节',{exact:true}).click();
    await popup.getByRole('button',{name:'降序',exact:true}).click();
    await expect.poll(async()=>await page.locator('.file-grid tbody tr td:nth-child(10) .file-cell-text').allTextContents()).toEqual(['32','29','27','25','23','21']);
    await page.locator('.file-name-link').first().click();
    await expect(page.getByRole('heading',{name:'文件详情',exact:true})).toBeVisible();
    await expect(page.locator('.file-details-grid')).toContainText('尚未核验附件内容');
    await expect(page.locator('.file-details-grid')).toContainText('关联文档编号');
    await page.screenshot({path:path.join(output,'files-details.png'),fullPage:false});
    await page.getByLabel('关闭文件详情',{exact:true}).click();
    await page.getByRole('button',{name:'清除全部筛选',exact:true}).click();
    await expect(count).toContainText('32 / 32');
    await page.getByRole('button',{name:'下一页',exact:true}).click();
    await expect(count).toContainText('第 2 / 2 页');
    await expect(page.locator('.file-grid tbody tr')).toHaveCount(12);
    await page.getByLabel('筛选 下载状态',{exact:true}).click();
    await popup.getByRole('button',{name:'全不选',exact:true}).click();
    await popup.locator('.file-filter-choice').filter({hasText:'待处理'}).locator('input').check();
    await popup.getByRole('button',{name:'应用筛选',exact:true}).click();
    await expect(count).toContainText('1 / 32');
    await expect(count).toContainText('第 1 / 1 页');
    await expect(page.locator('.file-grid tbody tr button[aria-label^="查看 "]')).toBeDisabled();
    await page.getByRole('button',{name:'清除全部筛选',exact:true}).click();
    await expect(count).toContainText('32 / 32');
    await page.setViewportSize({width:390,height:844});
    await page.getByLabel('筛选 业务类型',{exact:true}).click();
    await expect(popup).toBeVisible();
    const bounds=await popup.boundingBox();
    expect(bounds.x).toBeGreaterThanOrEqual(0);
    expect(bounds.x+bounds.width).toBeLessThanOrEqual(391);
    expect(bounds.y).toBeGreaterThanOrEqual(0);
    expect(bounds.y+bounds.height).toBeLessThanOrEqual(845);
    await popup.getByRole('button',{name:'取消',exact:true}).click();
    await expect(popup).toBeHidden();
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:path.join(output,'files-mobile.png'),fullPage:false});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
    expect(overflow).toBe(false);
    if(errors.length)throw Error(errors.join('\n'));
    console.log(JSON.stringify({passed:true,browser:'Edge via Playwright; Browser plugin not available',fixture:'32 files, actual classification rules; no external services',checks:['metadata','OR selections','AND columns','full dataset filtering','numeric range','numeric sorting','details with inheritance evidence','pagination reset','pending preview disabled','mobile popup and layout','no console errors'],screenshots:output}));
  }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)});
